def _raw(label: str, section: str, value: float) -> RawDatapoint:
    return RawDatapoint(
        id="figure-%s" % label[:6].replace(" ", ""),
        company_id="fixture_co",
        metric_raw=label,
        period_label="FY26",
        period_end_date=datetime(2026, 3, 31).date(),
        value=value,
        currency="INR",
        units="crores",
        source="nse_filing",
        source_location="fixture p.1",
        section=section,
        status="reported",
        update_date=datetime.now(),
    )


class TestTheCaptionsWithHomesReachThem:
    # Every map_raw_datapoints call in this file points the review queue at a
    # database of its own: runs used to write fixture_co rows into the shared
    # store, one set per test run.
    def test_each_reaches_its_key_with_the_printed_figure(self, tmp_path):
        for label, section, value, key in MAPPED_FIGURES:
            canonical, _mappings, unmapped = mapper.map_raw_datapoints(
                [_raw(label, section, value)], db_path=tmp_path / "queue.db"
            )
            keys = [c.canonical_key for c in canonical]
            assert keys == [key], (
                "%r reached %s; it belongs on %s, and the figure the filing "
                "prints under these exact words is %.0f" % (label, keys, key, value)
            )
            assert canonical[0].value == value, (
                "the figure moved on the way in: %r" % canonical[0].value
            )
            assert label not in unmapped, (
                "the caption is mapped by the registry but reported as a gap"
            )

    def test_each_is_registered_and_not_withdrawn(self):
        for label, _section, _value, _key in MAPPED_FIGURES:
            assert label in RAW_METRIC_MAP, (
                "the registry entry for %r is gone, so its key goes back to "
                "empty or to whatever the engine would suggest" % label
            )
            assert label not in WITHDRAWN_LABELS, (
                "%r cannot be both mapped and withdrawn; the registry lookup "
                "would succeed and the withdrawal would never be reached" % label
            )


class TestTheCaptionsWithoutAHomeAreRecorded:
    def test_every_one_of_them_is_a_withdrawn_label(self):
        missing = [
            label
            for label, _section, _value in WITHDRAWN_FIGURES
            if label not in WITHDRAWN_LABELS
        ]
        assert not missing, (
            "%r is not in WITHDRAWN_LABELS, so it reads as an unmapped accident "
            "rather than a recorded decision" % missing
        )
        assert len(WITHDRAWN_FIGURES) == 30, (
            "the family changed size (%d); add or remove the caption itself, not "
            "silently the count" % len(WITHDRAWN_FIGURES)
        )

    def test_none_of_them_is_also_in_the_registry(self):
        both = [
            label
            for label, _section, _value in WITHDRAWN_FIGURES
            if label in RAW_METRIC_MAP
        ]
        assert not both, (
            "%r is registered AND withdrawn, so the registry lookup wins and the "
            "withdrawal is inert" % both
        )

    def test_none_reaches_a_canonical_datapoint(self, tmp_path):
        for label, section, value in WITHDRAWN_FIGURES:
            canonical, _mappings, _unmapped = mapper.map_raw_datapoints(
                [_raw(label, section, value)], db_path=tmp_path / "queue.db"
            )
            leaked = [c for c in canonical if c.metric_raw == label]
            assert not leaked, (
                "%r reached canonical as %s = %.1f. Either no key holds this "
                "line honestly, or the only key that would take it states "
                "something false about what the figure is."
                % (
                    label,
                    ", ".join(sorted({c.canonical_key for c in leaked})),
                    leaked[0].value,
                )
            )

    def test_none_is_counted_as_an_unmapped_gap(self, tmp_path):
        """A recorded decision is not a coverage gap; the two states differ.

        An unmapped caption tells a reader something is missing. These are not
        missing -- they were looked at and deliberately kept out, and the review
        queue holds the name either way.
        """
        for label, section, value in WITHDRAWN_FIGURES:
            _canonical, _mappings, unmapped = mapper.map_raw_datapoints(
                [_raw(label, section, value)], db_path=tmp_path / "queue.db"
            )
            assert label not in unmapped, (
                "%r is reported unmapped, so the coverage count claims a gap that "
                "was already decided" % label
            )
