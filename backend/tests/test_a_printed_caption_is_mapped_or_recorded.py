"""A printed caption is either mapped to its key or recorded as withdrawn.

The Infosys documents print far more captions than the model consumes, and every
one of them has to be visible as a decision: mapped to a key that holds what the
caption says, or withdrawn with the reason on file. An unmapped caption reads as
an accident, and a caption the confidence engine parks on a key that states
something false about it is worse, because the wrong figure publishes under a
name that looks right.

Two families of decisions, made against the printed statements rather than the
names:

- Six captions have homes, and one memo beside them. "Payment of dividends" is the filing's own caption
  for the dividends line, read from the continuation page of both documents
  (printed 105 under 104, printed 111 under 110), and `canonical.cf.dividends_paid`
  was empty for this company because the aggregator's rows are refused by the
  statement guard. The four section totals and the printed bottom line are the
  statement's own skeleton: the sections sum to the bottom-line caption exactly
  in all three years (26,066 - 5,865 - 17,504 = 2,697 at FY24, and likewise at
  FY25 and FY26), which is the relationship the model derives the bottom line
  from, so the sections have to be the filing's totals and not whatever else the
  engine would suggest. The seventh is the filing's own exchange line, printed
  on the continuation page under the three sections ((84) / 82 / 1,600): the
  sections already sum to the bottom line without it, so it publishes as a
  memo outside them and the reconciliation check absorbs it.

- Thirty have none. The engine rates the first twenty-two low confidence
  (0.2, no key): their section totals are already mapped, and the balance-sheet
  cases cannot pick a key without replacing an aggregate with a component or
  putting two figures of one period under one identity. The next five the engine
  does suggest, at destinations that state something false: a pre-tax subtotal
  competing with the section total, a liability in an asset key, a deduction on
  the receipt line it adjusts, an ex-minority subtotal beside its own total, and
  a share-count note fragment on the liabilities-and-equity total. The last
  three the registry mapped itself, and each is a case where the cash flow
  statement's last-row rule lets page order publish a figure the filing does
  not support: the contingent line, beside the acquisition line it settles,
  overwrites the filing's (637) with its own (13); and the escrow pair, where
  deposits (1,815) and redemptions 1,815 net to zero for FY26 but the
  redemption prints last, so one side of a pair published as the year's line.
  Withdrawn is the recorded state for all thirty: no canonical datapoint, not
  counted as an unmapped gap, and a row in the review queue either way.
"""
